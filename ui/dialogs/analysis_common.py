class QuantityListPanel(QWidget):
    """Scrollable quantity list: add row / inline filter / delete."""

    changed = pyqtSignal()

    def __init__(self, parent=None, stretchable=False,
                 scroll_min_height=210):
        super().__init__(parent)
        self._rows = []
        self._stretchable = stretchable
        self._scroll_min_height = scroll_min_height
        self._build_ui()

    def _build_ui(self):
        v = QVBoxLayout(self)
        v.setContentsMargins(0, 0, 0, 0)
        v.setSpacing(6)

        header = QHBoxLayout()
        header.addWidget(QLabel("Quantity settings"))
        header.addStretch()
        add_btn = QPushButton("➕ Add quantity")
        add_btn.clicked.connect(self.add_row)
        header.addWidget(add_btn)
        v.addLayout(header)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        if self._stretchable:
            # Elastic height: the dialog layout distributes the extra
            # vertical space between the quantity/histogram areas so the
            # right panel fills the window instead of leaving gaps.
            scroll.setMinimumHeight(self._scroll_min_height)
        else:
            scroll.setFixedHeight(self._scroll_min_height)
        scroll.setHorizontalScrollBarPolicy(
            Qt.ScrollBarPolicy.ScrollBarAsNeeded)
        self._container = QWidget()
        self._container_layout = QVBoxLayout(self._container)
        self._container_layout.setContentsMargins(0, 0, 0, 0)
        self._container_layout.setSpacing(4)
        self._container_layout.addStretch()
        scroll.setWidget(self._container)
        v.addWidget(scroll)

    def add_row(self, q: dict = None):
        row = QuantityRowWidget()
        if q:
            row.set_quantity(q)
        else:
            names = [r.get_quantity()["name"] for r in self._rows]
            row.set_quantity({"name": gen_quantity_name(names),
                              "type": "energyDeposit", "filter": None})
        row.changed.connect(self.changed.emit)
        row.removed.connect(self._on_row_removed)
        self._rows.append(row)
        # Insert before the stretch item
        self._container_layout.insertWidget(
            self._container_layout.count() - 1, row)
        self.changed.emit()

    def _on_row_removed(self, row):
        if row in self._rows:
            self._rows.remove(row)
        self._container_layout.removeWidget(row)
        row.deleteLater()
        self.changed.emit()

    def get_quantities(self) -> list:
        return [r.get_quantity() for r in self._rows]

    def set_quantities(self, qs: list):
        # Clear
        for r in list(self._rows):
            self._on_row_removed(r)
        for q in qs:
            self.add_row(q)


