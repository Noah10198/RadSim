# -- Filter editor (expands inline in a single row) --

class FilterEditor(QWidget):
    """Filter editor: one row for the type, one row for the parameters
    (particle / energy range).

    The two-row layout keeps the widgets from overflowing horizontally in a
    narrow panel (parameter boxes running outside the window).
    None when no filter is set.
    """

    changed = pyqtSignal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self._build_ui()

    def _build_ui(self):
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(4)

        # Row 1: type
        row1 = QHBoxLayout()
        row1.setSpacing(6)
        row1.addWidget(QLabel("Filter:"))
        self._type_cb = QComboBox()
        self._type_cb.addItem("None", None)
        for key, label in FILTER_TYPES:
            self._type_cb.addItem(label, key)
        self._type_cb.currentIndexChanged.connect(self._on_type_changed)
        row1.addWidget(self._type_cb, 1)
        layout.addLayout(row1)

        # Row 2: parameters (particle / kinetic energy range)
        self._param_widget = QWidget()
        pw = QHBoxLayout(self._param_widget)
        pw.setContentsMargins(0, 0, 0, 0)
        pw.setSpacing(6)
        pw.addSpacing(44)  # align with the "Filter:" label in row 1
        self._particle_cb = QComboBox()
        self._particle_cb.addItems(PARTICLE_CHOICES)
        self._particle_cb.setMinimumWidth(110)
        pw.addWidget(self._particle_cb)
        self._min_spin = QDoubleSpinBox()
        self._min_spin.setRange(0.000001, 1e6)
        self._min_spin.setDecimals(4)
        self._min_spin.setValue(0.1)
        self._min_spin.setFixedWidth(95)
        pw.addWidget(self._min_spin)
        pw.addWidget(QLabel("–"))
        self._max_spin = QDoubleSpinBox()
        self._max_spin.setRange(0.000001, 1e6)
        self._max_spin.setDecimals(4)
        self._max_spin.setValue(100.0)
        self._max_spin.setFixedWidth(95)
        pw.addWidget(self._max_spin)
        self._unit_cb = QComboBox()
        self._unit_cb.addItems(ENERGY_UNITS)
        self._unit_cb.setFixedWidth(64)
        pw.addWidget(self._unit_cb)
        pw.addStretch()
        layout.addWidget(self._param_widget)

        self._particle_cb.currentIndexChanged.connect(self.changed.emit)
        self._min_spin.valueChanged.connect(self.changed.emit)
        self._max_spin.valueChanged.connect(self.changed.emit)
        self._unit_cb.currentIndexChanged.connect(self.changed.emit)
        self._on_type_changed()

    def _on_type_changed(self):
        t = self._type_cb.currentData()
        self._param_widget.setVisible(t is not None)
        self._particle_cb.setVisible(t in ("particle", "particleWithEnergy"))
        has_energy = t in ("kineticEnergy", "particleWithEnergy")
        self._min_spin.setVisible(has_energy)
        self._max_spin.setVisible(has_energy)
        self._unit_cb.setVisible(has_energy)
        self.changed.emit()

    def get_filter(self):
        t = self._type_cb.currentData()
        if t is None:
            return None
        if t == "particle":
            return {"t": "particle", "p": self._particle_cb.currentText()}
        if t == "kineticEnergy":
            return {"t": "kineticEnergy",
                    "min": self._min_spin.value(), "max": self._max_spin.value(),
                    "unit": self._unit_cb.currentText()}
        if t == "particleWithEnergy":
            return {"t": "particleWithEnergy", "p": self._particle_cb.currentText(),
                    "min": self._min_spin.value(), "max": self._max_spin.value(),
                    "unit": self._unit_cb.currentText()}
        if t == "charged":
            return {"t": "charged"}
        if t == "neutral":
            return {"t": "neutral"}
        return None

    def set_filter(self, f):
        if not f:
            idx = self._type_cb.findData(None)
            self._type_cb.setCurrentIndex(idx if idx >= 0 else 0)
            return
        t = f.get("t")
        idx = self._type_cb.findData(t)
        if idx >= 0:
            self._type_cb.setCurrentIndex(idx)
        p = f.get("p")
        if p:
            pi = self._particle_cb.findText(p)
            if pi >= 0:
                self._particle_cb.setCurrentIndex(pi)
        if "min" in f:
            self._min_spin.setValue(f["min"])
        if "max" in f:
            self._max_spin.setValue(f["max"])
        if f.get("unit"):
            ui = self._unit_cb.findText(f["unit"])
            if ui >= 0:
                self._unit_cb.setCurrentIndex(ui)


def filter_summary(f) -> str:
    """Short filter description used as the button text on a quantity row."""
    if not f:
        return "+ filter"
    t = f.get("t")
    if t == "particle":
        return f"✓ {f['p']}"
    if t == "kineticEnergy":
        return f"✓ {f['min']}–{f['max']}{f['unit']}"
    if t == "particleWithEnergy":
        return f"✓ {f['p']} {f['min']}–{f['max']}{f['unit']}"
    if t == "charged":
        return "✓ charged"
    if t == "neutral":
        return "✓ neutral"
    return "✓ filter"


# -- Quantity row --

class QuantityRowWidget(QFrame):
    """A single quantity row: name + type (fixed width) + unit column (fixed)
    + particle filter dropdown + delete."""

    changed = pyqtSignal()
    removed = pyqtSignal(object)

    def __init__(self, parent=None):
        super().__init__(parent)
        self._build_ui()

    def _build_ui(self):
        self.setFrameShape(QFrame.Shape.StyledPanel)
        # Themed "card": DIALOG_STYLE paints QFrame#rowCard with theme tokens
        # (both light/dark), so these rows never fall back to the default
        # (light) palette in dark mode.
        self.setObjectName("rowCard")
        v = QVBoxLayout(self)
        v.setContentsMargins(8, 6, 8, 6)
        v.setSpacing(4)

        row = QHBoxLayout()
        row.setSpacing(6)

        self._name_edit = QLineEdit()
        self._name_edit.setPlaceholderText("q1")
        self._name_edit.setFixedWidth(110)
        self._name_edit.textChanged.connect(self.changed.emit)
        row.addWidget(self._name_edit)

        self._type_cb = QComboBox()
        for key, _label, _u, _h in QUANTITY_TYPES:
            self._type_cb.addItem(key, key)
        # Fixed width: the dropdown no longer stretches across the row, so the
        # unit column stays at a stable position.
        self._type_cb.setFixedWidth(180)
        self._type_cb.currentIndexChanged.connect(self._on_type_changed)
        row.addWidget(self._type_cb)

        # Fixed-width unit column: aligned and never shifts when the type
        # (and therefore the unit text) changes.
        self._unit_label = QLabel("")
        # No explicit colour: inherit the dialog theme's text colour, so the
        # unit stays readable in both light and dark mode.
        self._unit_label.setStyleSheet(
            "font-family: Consolas; font-size: 11px;")
        self._unit_label.setFixedWidth(64)
        self._unit_label.setAlignment(Qt.AlignmentFlag.AlignCenter)
        row.addWidget(self._unit_label)

        # Particle filter as a single dropdown ("no filter" by default)
        self._filter_cb = QComboBox()
        self._filter_cb.addItem("no filter", None)
        for p in PARTICLE_CHOICES:
            self._filter_cb.addItem(p, p)
        self._filter_cb.setFixedWidth(120)
        self._filter_cb.currentIndexChanged.connect(self.changed.emit)
        row.addWidget(self._filter_cb)

        # Remaining space goes before the delete button, so the ✕ sits at the
        # right edge - aligned with the histogram rows' delete buttons.
        row.addStretch()

        del_btn = QPushButton("✕")
        del_btn.setFixedWidth(28)
        del_btn.setToolTip("Delete this quantity")
        del_btn.clicked.connect(lambda: self.removed.emit(self))
        row.addWidget(del_btn)

        v.addLayout(row)
        self._on_type_changed()

    def _on_type_changed(self):
        qtype = self._type_cb.currentData()
        unit, _hx = quantity_meta(qtype or "energyDeposit")
        self._unit_label.setText(f"[{unit}]" if unit else "[count]")
        self.changed.emit()

    def get_quantity(self) -> dict:
        p = self._filter_cb.currentData()
        return {
            "name": self._name_edit.text().strip() or "q",
            "type": self._type_cb.currentData() or "energyDeposit",
            "filter": {"t": "particle", "p": p} if p else None,
        }

    def set_quantity(self, q: dict):
        self._name_edit.setText(q.get("name", "q"))
        t = q.get("type", "energyDeposit")
        idx = self._type_cb.findData(t)
        if idx >= 0:
            self._type_cb.setCurrentIndex(idx)
        f = q.get("filter") or {}
        if f.get("t") == "particle":
            pidx = self._filter_cb.findData(f.get("p"))
            if pidx >= 0:
                self._filter_cb.setCurrentIndex(pidx)
        # Non-particle filters (legacy configs) fall back to "no filter".


