"""
analysis_common - UI widgets and metadata shared by the three analysis dialogs

Based on doc/solver_capability/README.md sections 5/6 and realworld_ui_design.md:
  - quantity type table (15 kinds, all available in realworld/probe; voxel uses
    the same quantities but has no energy spectrum)
  - 5 filter types (order-bound: a filter row follows its target quantity)
  - histogram targets are limited to quantities that "support fill1D" (10 kinds)
  - theming: dialogs define no hard-coded colors, they all consume the QSS
    generated by DIALOG_STYLE(dark)
"""

from PyQt6.QtWidgets import (
    QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton,
    QLineEdit, QComboBox, QDoubleSpinBox, QSpinBox, QCheckBox,
    QFrame, QScrollArea,
)
from PyQt6.QtCore import Qt, pyqtSignal

# -- Quantity type metadata --
# (key, display name, quantity unit, histogram x-axis unit or
#  None = no energy spectrum support)
QUANTITY_TYPES = [
    ("energyDeposit", "energyDeposit", "MeV", "MeV"),
    ("doseDeposit", "doseDeposit", "Gy", "Gy"),
    ("volumeFlux", "volumeFlux", "", "MeV"),
    ("nOfStep", "nOfStep", "", "mm"),
    ("nOfTrack", "nOfTrack", "", "MeV"),
    ("nOfSecondary", "nOfSecondary", "", "MeV"),
    ("cellFlux", "cellFlux", "cm⁻²", "MeV"),
    ("passageCellFlux", "passageCellFlux", "cm⁻²", "MeV"),
    ("passageCellCurrent", "passageCellCurrent", "", "MeV"),
    ("passageTrackLength", "passageTrackLength", "mm", "mm"),
    ("trackLength", "trackLength", "mm", None),
    ("cellCharge", "cellCharge", "e⁺", None),
    ("nOfCollision", "nOfCollision", "", None),
    ("nOfTerminatedTrack", "nOfTerminatedTrack", "", None),
    ("population", "population", "", None),
]

# filter types (Geant4 implements only these 5)
FILTER_TYPES = [
    ("particle", "Particle type"),
    ("kineticEnergy", "Kinetic energy range"),
    ("particleWithEnergy", "Particle + kinetic energy"),
    ("charged", "Charged particles"),
    ("neutral", "Neutral particles"),
]

PARTICLE_CHOICES = [
    "gamma", "e-", "e+", "proton", "neutron",
    "alpha", "He3", "deuteron", "triton",
    "mu-", "mu+", "pi-", "pi+",
]

ENERGY_UNITS = ["MeV", "keV", "GeV"]

MATERIAL_CHOICES = [
    "none", "G4_WATER", "G4_AIR", "G4_Al", "G4_Cu", "G4_Fe", "G4_Pb",
]


def quantity_meta(qtype: str):
    for key, _label, unit, hx_unit in QUANTITY_TYPES:
        if key == qtype:
            return unit, hx_unit
    return "", None


def supports_histogram(qtype: str) -> bool:
    return quantity_meta(qtype)[1] is not None


def gen_quantity_name(existing: list) -> str:
    n = len(existing) + 1
    while f"q{n}" in existing:
        n += 1
    return f"q{n}"


