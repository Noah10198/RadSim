class HistogramRowWidget(QFrame):
    """A single 1D-histogram row: target quantity + bins + range (the range
    unit follows the linked quantity) + log + delete."""

    changed = pyqtSignal()
    removed = pyqtSignal(object)

    def __init__(self, qnames: list, qunits: dict = None, parent=None):
        super().__init__(parent)
        self._qnames = qnames
        self._qunits = qunits or {}
        self._build_ui()

    def _build_ui(self):
        self.setFrameShape(QFrame.Shape.StyledPanel)
        self.setObjectName("rowCard")
        row = QHBoxLayout(self)
        row.setContentsMargins(8, 5, 8, 5)
        # Tight spacing keeps the row narrow enough that no horizontal
        # scroll bar appears in the right-hand panels of the dialogs.
        row.setSpacing(5)

        row.addWidget(QLabel("Quantity:"))
        # The target is typed like the quantity Name box instead of being
        # picked from a dropdown: new histogram rows auto-assign the defined
        # quantities in order (q1, q2, …), and the typed text is validated
        # against the defined quantities (see _refresh_target).
        self._q_edit = QLineEdit()
        self._q_edit.setPlaceholderText("q1")
        self._q_edit.setMinimumWidth(110)
        self._q_edit.textChanged.connect(self._on_q_changed)
        row.addWidget(self._q_edit, 1)

        row.addWidget(QLabel("bins:"))
        self._bins = QSpinBox()
        self._bins.setRange(2, 10000)
        self._bins.setValue(100)
        self._bins.valueChanged.connect(self.changed.emit)
        row.addWidget(self._bins)

        row.addWidget(QLabel("Range:"))
        self._min = QDoubleSpinBox()
        self._min.setRange(-1e12, 1e12)
        self._min.setDecimals(4)
        self._min.setValue(0.001)
        self._min.setFixedWidth(88)
        self._min.valueChanged.connect(self.changed.emit)
        row.addWidget(self._min)
        row.addWidget(QLabel("–"))
        self._max = QDoubleSpinBox()
        self._max.setRange(-1e12, 1e12)
        self._max.setDecimals(4)
        self._max.setValue(1000.0)
        self._max.setFixedWidth(88)
        self._max.valueChanged.connect(self.changed.emit)
        row.addWidget(self._max)

        # Range unit (MeV / mm / ...) follows the selected quantity. No
        # explicit colour: inherits the theme's text colour (light/dark).
        self._unit_label = QLabel("")
        self._unit_label.setStyleSheet(
            "font-family: Consolas; font-size: 11px;")
        self._unit_label.setFixedWidth(40)
        row.addWidget(self._unit_label)

        self._log = QCheckBox("log")
        self._log.stateChanged.connect(self.changed.emit)
        row.addWidget(self._log)

        del_btn = QPushButton("✕")
        del_btn.setFixedWidth(28)
        del_btn.clicked.connect(lambda: self.removed.emit(self))
        row.addWidget(del_btn)

        self._set_choices(self._qnames, self._qunits)

    def _set_choices(self, qnames: list, qunits: dict = None):
        """Refresh the set of DEFINED quantities that validate the typed
        target and resolve its x-axis unit. Never overwrites the text the
        user typed."""
        self._qnames = qnames or []
        self._qunits = qunits or {}
        self._refresh_target()

    def _refresh_target(self):
        """Re-validate the typed quantity name and update the range-unit
        column. A name that matches no defined quantity gets a red outline
        (mac_builder silently drops histogram rows whose target quantity is
        not defined on the same mesh)."""
        name = self.get_qname()
        unit = self._qunits.get(name, "")
        self._unit_label.setText(unit if unit else "")
        ok = (not name) or (name in self._qnames)
        self._q_edit.setStyleSheet(
            "" if ok else "QLineEdit { border: 1px solid #d34f4f; }")
        return ok

    def set_qname(self, name: str):
        """Typed target quantity (textChanged -> _on_q_changed emits changed)."""
        self._q_edit.setText(name or "")

    def get_qname(self) -> str:
        return self._q_edit.text().strip()

    def _on_q_changed(self, *_):
        self._refresh_target()
        self.changed.emit()

    def get_histogram(self) -> dict:
        return {
            "q": self.get_qname(),
            "bins": self._bins.value(),
            "rng": [self._min.value(), self._max.value()],
            "log": self._log.isChecked(),
        }

    def set_histogram(self, h: dict):
        self.set_qname(h.get("q", ""))
        self._bins.setValue(h.get("bins", 100))
        rng = h.get("rng", [0.001, 1000.0])
        self._min.setValue(rng[0])
        self._max.setValue(rng[1])
        self._log.setChecked(h.get("log", False))


class HistogramListPanel(QWidget):
    """Energy-spectrum histogram list (probe/realworld only; hidden in
    voxel)."""

    changed = pyqtSignal()

    def __init__(self, parent=None, stretchable=False,
                 scroll_min_height=150):
        super().__init__(parent)
        self._rows = []
        self._stretchable = stretchable
        self._scroll_min_height = scroll_min_height
        self._build_ui()

    def _build_ui(self):
        v = QVBoxLayout(self)
        v.setContentsMargins(0, 0, 0, 0)
        v.setSpacing(6)

        header = QHBoxLayout()
        header.addWidget(QLabel("1D histogram"))
        header.addStretch()
        add_btn = QPushButton("➕ Add histogram")
        add_btn.clicked.connect(self.add_row)
        header.addWidget(add_btn)
        v.addLayout(header)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        if self._stretchable:
            scroll.setMinimumHeight(self._scroll_min_height)
        else:
            scroll.setFixedHeight(self._scroll_min_height)
        scroll.setHorizontalScrollBarPolicy(
            Qt.ScrollBarPolicy.ScrollBarAsNeeded)
        self._container = QWidget()
        self._container_layout = QVBoxLayout(self._container)
        self._container_layout.setContentsMargins(0, 0, 0, 0)
        self._container_layout.setSpacing(4)
        self._container_layout.addStretch()
        scroll.setWidget(self._container)
        v.addWidget(scroll)

    def _usable_qnames(self) -> list:
        return self._qnames if hasattr(self, "_qnames") else []

    def set_qnames(self, qnames: list, units: dict = None):
        """Candidate target quantities = names of the quantities in the
        current panel that support fill1D (units maps name -> range unit).

        Update and emit the signal only when the candidates really change
        (to avoid a changed -> sync -> changed infinite loop).
        """
        if (getattr(self, "_qnames", None) == qnames
                and getattr(self, "_qunits", None) == units):
            return
        self._qnames = qnames
        self._qunits = units or {}
        for r in self._rows:
            # Keeps the typed text, only re-validates it and refreshes the
            # x-axis unit for the current quantity list.
            r._set_choices(qnames, self._qunits)
        self.changed.emit()

    def _next_free_qname(self) -> str:
        """First defined quantity (in definition order) that is not yet the
        target of any histogram row, so consecutive Add clicks map to
        q1, q2, q3, … in lockstep with the quantity list."""
        names = self._usable_qnames()
        if not names:
            return ""
        used = {r.get_histogram().get("q") for r in self._rows}
        for n in names:
            if n not in used:
                return n
        return names[0]

    def add_row(self, h: dict = None):
        names = self._usable_qnames()
        if not names:
            return
        row = HistogramRowWidget(names, getattr(self, "_qunits", {}))
        if h:
            row.set_histogram(h)
        else:
            # Auto-assign the next quantity that has no histogram yet, so the
            # new row lines up with the quantity list instead of always
            # defaulting to the first quantity.
            row.set_histogram({"q": self._next_free_qname()})
        row.changed.connect(self.changed.emit)
        row.removed.connect(self._on_row_removed)
        self._rows.append(row)
        self._container_layout.insertWidget(
            self._container_layout.count() - 1, row)
        self.changed.emit()

    def _on_row_removed(self, row):
        if row in self._rows:
            self._rows.remove(row)
        self._container_layout.removeWidget(row)
        row.deleteLater()
        self.changed.emit()

    def get_histograms(self) -> list:
        return [r.get_histogram() for r in self._rows]

    def set_histograms(self, hs: list):
        for r in list(self._rows):
            self._on_row_removed(r)
        for h in hs:
            self.add_row(h)
